/**
 * BUSINESSES - every trade in Willowbrook and Ashford City (owner: economy domain).
 *
 * 22 canonical business ids from src/data/shops/ids.ts. Each entry defines opening hours,
 * a starter stock list (8-20 lines), wages/jobs and an owner. Businesses with
 * ownerNpcId === null and a purchasable type advertise themselves as for sale to the player.
 *
 * Convention: businesses run inside the building interior where one exists
 * (interiorIdFor(exteriorId)); open-air trades (market stalls) and the farm use the exterior
 * location. A local weekly closing rule (e.g. the museum shut on Mondays) is applied by
 * EconomySystem/BusinessSystem as a documented balance constant, not by this data file.
 */

function stock(itemId: ItemId, quantity: number, restockTarget: number, priceMultiplier = 1): ShopStockSeed {
  return { itemId, quantity, priceMultiplier, restockTarget };
}

function job(
  title: string,
  wagePerHour: number,
  startHour: number,
  endHour: number,
  slots: number,
  skill: SkillId | null,
  levelReq: number,
  playerAvailable: boolean
): JobDefSeed {
  const seed: JobDefSeed = { title, wagePerHour, startHour, endHour, slots, levelReq, playerAvailable };
  if (skill) seed.skill = skill;
  return seed;
}

