const WILLOWBROOK_EXT = WILLOWBROOK_EXTERIOR_SEEDS.map((seed) => makeExterior(seed, WILLOWBROOK_REGION));
const ASHFORD_EXT = ASHFORD_EXTERIOR_SEEDS.map((seed) => makeExterior(seed, ASHFORD_REGION));

const EXTERIOR_BY_ID = new Map<LocationId, LocationDef>();
for (const def of [...WILLOWBROOK_EXT, ...ASHFORD_EXT]) {
  if (EXTERIOR_BY_ID.has(def.id)) throw new Error('Duplicate exterior location id: ' + def.id);
  EXTERIOR_BY_ID.set(def.id, def);
}

function applyEdges(edges: readonly (readonly [LocationId, LocationId])[]): void {
  for (const [a, b] of edges) {
    const from = EXTERIOR_BY_ID.get(a);
    const to = EXTERIOR_BY_ID.get(b);
    if (!from) throw new Error('World edge references unknown exterior: ' + a);
    if (!to) throw new Error('World edge references unknown exterior: ' + b);
    if (!from.connections.includes(b)) from.connections.push(b);
    if (!to.connections.includes(a)) to.connections.push(a);
  }
}

applyEdges(WILLOWBROOK_EDGES);
applyEdges(ASHFORD_EDGES);

const INTERIORS: LocationDef[] = [];
for (const seed of [...WILLOWBROOK_INTERIOR_SEEDS, ...ASHFORD_INTERIOR_SEEDS]) {
  const exterior = EXTERIOR_BY_ID.get(seed.exteriorId);
  if (!exterior) throw new Error('Interior references unknown exterior: ' + seed.exteriorId);
  INTERIORS.push(makeInterior(seed, exterior));
}

// The travel graph is undirected: an interior is a walk neighbour of its own
// exterior, so the exterior lists its interior too (the front door). This keeps
// naive graph walkers (map UI, scene exit lists, integration harnesses) able to
// find building entrances without knowing the interior-id convention.
for (const interior of INTERIORS) {
  const entranceId = interior.entranceFrom;
  if (!entranceId) continue;
  const exterior = EXTERIOR_BY_ID.get(entranceId);
  if (exterior && !exterior.connections.includes(interior.id)) exterior.connections.push(interior.id);
}

/** Every location in the world (exteriors first, interiors after). */
export const LOCATIONS: LocationDef[] = [...WILLOWBROOK_EXT, ...ASHFORD_EXT, ...INTERIORS];
