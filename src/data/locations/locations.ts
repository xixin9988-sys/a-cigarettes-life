/**
 * OWNER: Agent 4 (World & Map).
 *
 * Complete static location graph for the game:
 *  - 25 Willowbrook exteriors
 *  - 20 Ashford City exteriors
 *  - one enterable interior for every building the player can step into
 *
 * Layout:
 *  - `mapX`/`mapY` are the location's centre in overworld tiles (32px tiles).
 *  - `widthTiles`/`heightTiles` are the scene footprint; a location scene is
 *    `widthTiles * tileSize` wide and the player is placed at its centre in pixels.
 *  - Exterior connections are undirected; the edge list below is declared once and
 *    mirrored into both endpoints so the graph can never drift out of sync.
 *  - Interiors connect only to their own exterior (`entranceFrom`).
 */

// ---------------------------------------------------------------------------
// Seed types + builders
// ---------------------------------------------------------------------------

interface ExteriorSeed {
  id: LocationId;
  name: string;
  kind: LocationKind;
  description: string;
  mapX: number;
  mapY: number;
  widthTiles: number;
  heightTiles: number;
  theme: LocationDef['theme'];
  floorColor: string;
  accentColor: string;
  visual: ItemVisual;
  openHour?: number;
  closeHour?: number;
  shelter?: number;
  windExposure?: number;
  humidityModifier?: number;
  heatSource?: boolean;
  facilities?: FacilityKind[];
  fishSpot?: FishSpotDef;
  eventTags?: string[];
  forageTags?: string[];
  discoverable?: boolean;
  secret?: boolean;
  clueRequirement?: number;
  /** Business that operates at this exterior (open-air market / farm shop). */
  businessId?: BusinessId;
}

interface InteriorSeed {
  exteriorId: LocationId;
  name: string;
  description: string;
  widthTiles: number;
  heightTiles: number;
  floorColor: string;
  accentColor: string;
  visual: ItemVisual;
  openHour?: number;
  closeHour?: number;
  facilities?: FacilityKind[];
  businessId?: BusinessId;
  heatSource?: boolean;
  humidityModifier?: number;
  eventTags?: string[];
  discoverable?: boolean;
  secret?: boolean;
  clueRequirement?: number;
}

function makeExterior(seed: ExteriorSeed, regionId: RegionId): LocationDef {
  const def: LocationDef = {
    id: seed.id,
    name: seed.name,
    regionId,
    kind: seed.kind,
    description: seed.description,
    indoor: false,
    mapX: seed.mapX,
    mapY: seed.mapY,
    widthTiles: seed.widthTiles,
    heightTiles: seed.heightTiles,
    connections: [],
    shelter: seed.shelter ?? 0.12,
    windExposure: seed.windExposure ?? 0.55,
    humidityModifier: seed.humidityModifier ?? 0,
    heatSource: seed.heatSource ?? false,
    openHour: seed.openHour ?? 0,
    closeHour: seed.closeHour ?? 24,
    facilities: seed.facilities ? [...seed.facilities] : [],
    eventTags: seed.eventTags ? [...seed.eventTags] : [],
    forageTags: seed.forageTags ? [...seed.forageTags] : [],
    discoverable: seed.discoverable ?? true,
    secret: seed.secret ?? false,
    theme: seed.theme,
    visual: seed.visual,
    floorColor: seed.floorColor,
    accentColor: seed.accentColor,
  };
  if (seed.fishSpot !== undefined) def.fishSpot = { ...seed.fishSpot };
  if (seed.clueRequirement !== undefined) def.clueRequirement = seed.clueRequirement;
  if (seed.businessId !== undefined) def.businessId = seed.businessId;
  return def;
}

function makeInterior(seed: InteriorSeed, exterior: LocationDef): LocationDef {
  const def: LocationDef = {
    id: interiorIdFor(seed.exteriorId),
    name: seed.name,
    regionId: exterior.regionId,
    kind: 'interior',
    description: seed.description,
    indoor: true,
    entranceFrom: seed.exteriorId,
    mapX: exterior.mapX,
    mapY: exterior.mapY,
    widthTiles: seed.widthTiles,
    heightTiles: seed.heightTiles,
    connections: [seed.exteriorId],
    shelter: 1,
    windExposure: 0,
    humidityModifier: seed.humidityModifier ?? 0,
    heatSource: seed.heatSource ?? false,
    openHour: seed.openHour ?? 8,
    closeHour: seed.closeHour ?? 20,
    facilities: seed.facilities ? [...seed.facilities] : [],
    eventTags: seed.eventTags ? [...seed.eventTags] : [],
    forageTags: [],
    discoverable: seed.discoverable ?? false,
    secret: seed.secret ?? false,
    theme: 'indoor',
    visual: seed.visual,
    floorColor: seed.floorColor,
    accentColor: seed.accentColor,
  };
  if (seed.businessId !== undefined) def.businessId = seed.businessId;
  if (seed.clueRequirement !== undefined) def.clueRequirement = seed.clueRequirement;
  return def;
}

